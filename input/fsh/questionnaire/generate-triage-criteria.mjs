// Generates TriageCriteriaItems.fsh, the triage criteria items of the WEST-A Triage
// Questionnaire, from the WEST-A triage criterion code system. Run it after changing the code
// system: node input/fsh/questionnaire/generate-triage-criteria.mjs
//
// Each chief complaint with warning symptoms gets its own repeating item, enabled when that
// complaint is chosen, that offers only the criteria whose complaint property is that
// complaint. For gynaecology (11) and trauma (30), whose criteria the manual groups under
// headings, the item is a group with one repeating item per heading; the heading codes are not
// selectable, so they are item texts and never answers. "No warning symptoms" and the needs and
// processes are offered whatever the complaint.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const codeSystem = JSON.parse(
  readFileSync(join(root, 'input/vocabulary/CodeSystem-west-a-triage-criterion-cs.json'), 'utf8'),
);

const COMPLAINTS = 31;
const NO_WARNING_SYMPTOMS = '163';
const NEEDS_HEADING = 'AAK';

const property = (concept, code) =>
  (concept.property ?? []).filter((p) => p.code === code).map((p) => p.valueCoding?.code ?? p.valueCode);
const english = (concept) => {
  const designation = (concept.designation ?? []).find((d) => d.language === 'en');
  if (!designation) throw new Error(`Criterion ${concept.code} has no English designation`);
  return designation.value;
};
const isHeading = (concept) => (concept.property ?? []).some((p) => p.code === 'notSelectable' && p.valueBoolean);
const byCode = (a, b) => Number(a.code) - Number(b.code);

const concepts = codeSystem.concept;
const criteria = concepts.filter((c) => !isHeading(c));
const headings = concepts.filter(isHeading);
const find = (code) => concepts.find((c) => c.code === code) ?? fail(`No criterion ${code}`);
function fail(message) {
  throw new Error(message);
}

const lines = [];
const out = (line = '') => lines.push(line);

function option(path, concept) {
  out(`* ${path}answerOption[+].valueCoding = $west-a-triage-criterion#${concept.code} "${english(concept)}"`);
}

// A repeating choice item with check boxes, at path (ending in "item[=]."), for the criteria
function criteriaItem(path, linkId, text, options) {
  out(`* ${path.replace(/\[=\]\.$/, '[+]')}.linkId = "${linkId}"`);
  out(`* ${path}type = #choice`);
  out(`* ${path}text = "${text}"`);
  out(`* ${path}repeats = true`);
  out(`* ${path.slice(0, -1)} insert ItemControl(check-box)`);
  for (const concept of options) option(path, concept);
}

function complaintCondition(path, complaint) {
  out(`* ${path}enableWhen[0].question = "chief-complaint"`);
  out(`* ${path}enableWhen[0].operator = #=`);
  out(`* ${path}enableWhen[0].answerCoding = ChiefComplaintCS#${complaint}`);
}

out('// Generated by generate-triage-criteria.mjs from the WEST-A triage criterion code system:');
out('// do not edit by hand.');
out();
out('// The items of the triage criteria group: the warning symptoms of each chief complaint,');
out('// "No warning symptoms", and the needs and processes');
out('RuleSet: TriageCriteriaItems');

const summary = [];
for (let complaint = 1; complaint <= COMPLAINTS; complaint++) {
  const own = criteria.filter((c) => property(c, 'complaint').includes(String(complaint))).sort(byCode);
  if (!own.length) {
    summary.push(`${complaint}: only ${NO_WARNING_SYMPTOMS}`);
    continue;
  }
  const ownHeadings = headings.filter((h) => property(h, 'complaint').includes(String(complaint)));
  out();
  if (!ownHeadings.length) {
    criteriaItem('item[=].', `triage-criteria-${complaint}`, 'Warning symptoms', own);
    complaintCondition('item[=].', complaint);
    summary.push(`${complaint}: ${own.map((c) => c.code).join(' ')}`);
    continue;
  }
  // Gynaecology and trauma: a group with an item per heading
  out(`* item[+].linkId = "triage-criteria-${complaint}"`);
  out('* item[=].type = #group');
  out('* item[=].text = "Warning symptoms"');
  complaintCondition('item[=].', complaint);
  for (const heading of ownHeadings.sort((a, b) => a.code.localeCompare(b.code))) {
    const underHeading = own.filter((c) => property(c, 'parent').includes(heading.code));
    if (!underHeading.length) fail(`Heading ${heading.code} has no criteria`);
    criteriaItem('item[=].item[=].', `triage-criteria-${complaint}-${heading.code.toLowerCase()}`, english(heading), underHeading);
    summary.push(`${complaint} ${heading.code}: ${underHeading.map((c) => c.code).join(' ')}`);
  }
  const ungrouped = own.filter((c) => !ownHeadings.some((h) => property(c, 'parent').includes(h.code)));
  if (ungrouped.length) fail(`Complaint ${complaint} has criteria outside its headings: ${ungrouped.map((c) => c.code)}`);
}

out();
criteriaItem('item[=].', 'triage-criteria-none', 'No warning symptoms', [find(NO_WARNING_SYMPTOMS)]);
out();
const needs = criteria.filter((c) => property(c, 'parent').includes(NEEDS_HEADING)).sort(byCode);
criteriaItem('item[=].', 'triage-criteria-needs', english(find(NEEDS_HEADING)), needs);

writeFileSync(join(here, 'TriageCriteriaItems.fsh'), `${lines.join('\n')}\n`);
console.log(summary.join('\n'));
